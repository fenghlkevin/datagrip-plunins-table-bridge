        check(KeyCursor.decode(KeyCursor.encode(cursor)).equals(cursor),"typed composite key cursor round trip");
        check(KeyCursor.after(Engine.POSTGRES,List.of("a","b")).equals("((\"a\">?) OR (\"a\"=? AND \"b\">?))"),"keyset lexicographic predicate");
        check(DurableRunner.transientFailure(new SQLException("deadlock","40001")),"transaction conflict permits checkpoint retry");
        check(!DurableRunner.transientFailure(new SQLException("syntax","42000")),"syntax failure never retries");
        var oracleIdentity=OracleIdentity.prepare("CREATE TABLE \"S\".\"T\" (\"id\" NUMBER(20,0) GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),\"n\" VARCHAR2(30))",List.of("id"),"\"S\".\"T\"");
        check(oracleIdentity.create().contains("GENERATED BY DEFAULT AS IDENTITY")&&oracleIdentity.after().getFirst().contains("GENERATED ALWAYS AS IDENTITY (START WITH LIMIT VALUE)"),"Oracle identity imports explicit values then restores generation strategy");
        check(Engine.MYSQL.quote("a`b").equals("`a``b`"),"MySQL quoting");
        check(Engine.MSSQL.quote("a]b").equals("[a]]b]"),"SQL Server quoting");
        check(Engine.POSTGRES.quote("a\"b").equals("\"a\"\"b\""),"PG quoting");
