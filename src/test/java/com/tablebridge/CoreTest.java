        SqlNames.requireCreateOnly("CREATE TABLE t (id int)");
        fails(()->SqlNames.rebase("CREATE TABLE source_db.public.t (id int)",Engine.POSTGRES,"public","dest",Map.of()),"three-part names cannot write to source catalog");
