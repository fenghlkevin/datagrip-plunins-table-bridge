        check(mapped.contains("\"archive\".\"orders_copy\""),"qualified name remap");
        check(mapped.contains("'keep this'")&&mapped.endsWith("-- public.orders"),"preserve text/comments");
        check(SqlNames.rebase("CREATE TABLE public.orders (id int REFERENCES public.users)",Engine.POSTGRES,"public","dest",Map.of("orders","o","users","u")).contains("REFERENCES \"dest\".\"u\""),"dependencies remap");
        String seq=SqlNames.rebase("CREATE TABLE public.t (id int DEFAULT nextval('public.t_id_seq'::regclass))",Engine.POSTGRES,"public","dest",Map.of());
        check(seq.contains("'\"dest\".\"t_id_seq\"'::regclass"),"serial namespace remap");
        fails(()->SqlNames.rebase("CREATE FUNCTION public.f() RETURNS void AS $$ SELECT * FROM public.t $$ LANGUAGE sql",Engine.POSTGRES,"public","dest",Map.of()),"do not silently change function bodies");
        fails(()->SqlNames.requireCreateOnly("DROP TABLE source.orders"),"block drop");
